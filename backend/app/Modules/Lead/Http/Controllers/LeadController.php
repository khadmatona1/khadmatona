<?php

namespace App\Modules\Lead\Http\Controllers;

use App\Models\User;
use App\Core\Support\Http\ApiResponse;
use App\Modules\Lead\Domain\Contracts\LeadRepositoryInterface;
use App\Modules\Lead\Domain\Enums\LeadStatus;
use App\Modules\Lead\Domain\Models\Lead;
use App\Modules\Lead\Http\Filters\LeadFilter;
use App\Modules\Lead\Http\Requests\UpdateLeadContactRequest;
use App\Modules\Lead\Http\Requests\UpdateLeadStatusRequest;
use App\Modules\Lead\Http\Resources\AdminLeadResource;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\Gate;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\Rule;
use Illuminate\Validation\ValidationException;

/**
 * Shared between Admin (sees every lead) and Commercial (sees only leads
 * generated by their own properties, enforced by LeadFilter's row scoping
 * for index() and LeadPolicy for show()/updateStatus()) - simple CRUD, no
 * Service layer, same carve-out PropertyController uses
 * (PROJECT_RULES.md §6). destroy() stays Admin-only at the route level, no
 * policy needed. The public capture endpoint lives separately in
 * StoreLeadController.
 */
class LeadController
{
    public function __construct(private readonly LeadRepositoryInterface $leads) {}

    public function index(Request $request, LeadFilter $filter): JsonResponse
    {
        $leads = $filter->apply()->paginate($request->integer('per_page', 15));

        return ApiResponse::success(
            AdminLeadResource::collection($leads)->resolve(),
            ['pagination' => [
                'current_page' => $leads->currentPage(),
                'last_page' => $leads->lastPage(),
                'per_page' => $leads->perPage(),
                'total' => $leads->total(),
            ]]
        );
    }

    public function show(Lead $lead): JsonResponse
    {
        Gate::authorize('view', $lead);

        $lead->load('media');

        return ApiResponse::success(new AdminLeadResource($lead));
    }

    public function assignmentOptions(): JsonResponse
    {
        return ApiResponse::success(User::role(['Commercial', 'SeniorCommercial'])
            ->where('is_active', true)->orderBy('name')->get(['id', 'name']));
    }

    public function assign(Request $request): JsonResponse
    {
        $data = $request->validate([
            'lead_ids' => ['required', 'array', 'min:1', 'max:500'],
            'lead_ids.*' => ['required', 'integer', 'distinct'],
            'commercial_id' => ['required', 'integer', Rule::exists('users', 'id')->where('is_active', true)],
        ]);

        $count = DB::transaction(function () use ($data) {
            $commercial = User::query()->lockForUpdate()->find($data['commercial_id']);
            if (! $commercial?->is_active || ! $commercial->hasAnyRole(['Commercial', 'SeniorCommercial'])) {
                throw ValidationException::withMessages(['commercial_id' => 'Choose an active commercial.']);
            }
            $leads = Lead::query()->whereIn('id', $data['lead_ids'])->orderBy('id')->lockForUpdate()->get();
            if ($leads->count() !== count($data['lead_ids'])) {
                throw ValidationException::withMessages(['lead_ids' => 'One or more leads no longer exist.']);
            }
            foreach ($leads as $lead) {
                $this->leads->update($lead, ['commercial_id' => $commercial->id, 'callback_notified_at' => null]);
            }

            return $leads->count();
        });

        return ApiResponse::success(['assigned' => $count]);
    }

    public function updateStatus(UpdateLeadStatusRequest $request, Lead $lead): JsonResponse
    {
        Gate::authorize('updateStatus', $lead);

        $data = $request->validated();

        // The callback timer belongs to "À rappeler" only: entering (or
        // re-saving) it (re)arms the reminder, any other status disarms it.
        $lead = $this->leads->update($lead, [
            'status' => $data['status'],
            'callback_at' => $data['status'] === LeadStatus::ToCallBack->value ? Carbon::parse($data['callback_at']) : null,
            'callback_notified_at' => null,
        ]);

        return ApiResponse::success(new AdminLeadResource($lead));
    }

    public function destroy(Lead $lead): JsonResponse
    {
        $this->leads->delete($lead);

        return ApiResponse::success();
    }

    /**
     * Links (or unlinks, with `contact_id: null`) this lead to a Contact -
     * never auto-set at capture time, always an explicit dashboard action.
     */
    public function updateContact(UpdateLeadContactRequest $request, Lead $lead): JsonResponse
    {
        Gate::authorize('manageContact', $lead);

        $lead = $this->leads->update($lead, $request->validated());

        return ApiResponse::success(new AdminLeadResource($lead));
    }
}
